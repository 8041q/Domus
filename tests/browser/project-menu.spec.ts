import { modelBytes } from '../helpers/model.mjs';
import { test, expect } from '@playwright/test';

for (const width of [1440, 390, 320]) test(`project actions distinguish files, saved rooms and storage at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 900 });
  await page.goto('/');
  const project = page.getByRole('button', { name: 'Project', exact: true });
  await expect(project).toBeEnabled();
  if (width <= 820) await page.getByRole('navigation', { name: 'Phone workspace' }).getByRole('button', { name: 'Furniture', exact: true }).click();
  else await page.getByRole('button', { name: 'Plan room', exact: true }).click();
  await project.click();
  for (const label of [/^Save /, /^Open saved room/, /^Export room/, /^Import room/, /^Export to PDF/]) await expect(page.getByRole('menuitem', { name: label })).toBeVisible();
  await expect(page.getByRole('menuitem', { name: /Storage|Save as|Download room|Export 3D model/ })).toHaveCount(0);
  await expect(page.getByRole('menuitem', { name: /^Export room/ })).toHaveCount(1);
  await page.screenshot({ path: info.outputPath(`project-menu-${width}.png`) });
  await page.getByRole('menuitem', { name: /^Project details/ }).click();
  for (const name of ['Project', 'Room', 'Company & client', 'Notes']) await expect(page.getByRole('group', { name, exact: true })).toBeVisible();
  await page.getByLabel('Project', { exact: true }).fill('Room-42');
  await page.getByLabel('Company', { exact: true }).fill('Example company');
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Keep these project details');
  await page.getByRole('dialog').evaluate(element => element.scrollTop = 0);
  if (width === 1440) expect((await page.getByRole('dialog').boundingBox())!.height).toBeLessThan(780);
  await page.screenshot({ path: info.outputPath(`project-details-${width}.png`) });
  await page.getByLabel('Client', { exact: true }).fill('Example client company');
  await page.getByLabel('Site', { exact: true }).fill('Lisbon');
  await page.getByRole('button', { name: 'Add contact', exact: true }).click();
  const contact = page.getByRole('group', { name: 'Client contact 1', exact: true });
  await contact.getByLabel('Contact name', { exact: true }).fill('Jane Smith');
  await contact.getByLabel('Phone', { exact: true }).fill('+351 210 000 000');
  await contact.getByLabel('Email', { exact: true }).fill('jane@example.test');
  await page.getByRole('button', { name: 'Add contact', exact: true }).click();
  await page.getByRole('group', { name: 'Client contact 2', exact: true }).getByLabel('Email', { exact: true }).fill('temporary@example.test');
  await page.getByRole('button', { name: 'Remove client contact 2', exact: true }).click();
  await expect(page.getByRole('group', { name: 'Client contact 2', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Add contact', exact: true }).click();
  await page.getByRole('group', { name: 'Client contact 2', exact: true }).getByLabel('Email', { exact: true }).fill('accounts@example.test');
  await page.screenshot({ path: info.outputPath(`project-contacts-${width}.png`) });
  await page.getByRole('button', { name: 'Apply details', exact: true }).click();
  await project.click();
  await page.getByRole('menuitem', { name: /^Save / }).click();
  await page.getByRole('textbox', { name: 'Room name', exact: true }).fill('Menu project');
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(page.locator('.project-status')).toContainText('Menu project');
  await page.reload();
  await expect(project).toBeEnabled();
  await project.click();
  await page.getByRole('menuitem', { name: /^Project details/ }).click();
  await expect(page.getByLabel('Project', { exact: true })).toHaveValue('Room-42');
  await expect(page.getByLabel('Company', { exact: true })).toHaveValue('Example company');
  await expect(page.getByLabel('Client', { exact: true })).toHaveValue('Example client company');
  await expect(page.getByLabel('Site', { exact: true })).toHaveValue('Lisbon');
  const savedContact = page.getByRole('group', { name: 'Client contact 1', exact: true });
  await expect(savedContact.getByLabel('Contact name', { exact: true })).toHaveValue('Jane Smith');
  await expect(savedContact.getByLabel('Phone', { exact: true })).toHaveValue('+351 210 000 000');
  await expect(savedContact.getByLabel('Email', { exact: true })).toHaveValue('jane@example.test');
  await expect(page.getByRole('group', { name: 'Client contact 2', exact: true }).getByLabel('Email', { exact: true })).toHaveValue('accounts@example.test');
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Keep these project details');
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await project.click();
  await page.getByRole('menuitem', { name: /^Open saved room/ }).click();
  await expect(page.getByRole('button', { name: /^Menu project/ })).toBeVisible();
  await page.getByRole('button', { name: 'Storage & recovery', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Storage & recovery', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Back to saved rooms', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Open saved room', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Import room', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Import room', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Open saved room', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await project.click();
  await page.getByRole('menuitem', { name: /^Import room/ }).click();
  const importer = page.getByRole('dialog', { name: 'Import room', exact: true });
  await expect(importer).toContainText('.glb');
  await expect(importer).toContainText('.domus');
  await expect(importer).toContainText('.json');
  await expect(importer).toContainText('A regular GLB model cannot be imported as a room');
  await page.getByLabel('Import Domus draft').setInputFiles({ name: 'random-model.glb', mimeType: 'model/gltf-binary', buffer: Buffer.from(modelBytes()) });
  await expect(importer.getByRole('alert')).toContainText('no editable room data');
  await expect(page.locator('.project-status')).toContainText('Menu project');
  await page.screenshot({ path: info.outputPath(`project-import-${width}.png`) });
  await importer.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
});
